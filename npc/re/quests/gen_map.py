def generate_map():
    """Generate translation_map.txt from all strings."""
    strings = load_strings()
    lines = []
    translated = 0
    unchanged = 0

    for s in strings:
        t = tr(s)
        if t != s:
            translated += 1
        else:
            unchanged += 1
        lines.append(f"{s}|||{t}")

    with open(os.path.join(BASEDIR, 'translation_map.txt'), 'w', encoding='utf-8') as f:
        for line in lines:
            f.write(line + '\n')

    print(f"Generated translation_map.txt")
    print(f"  Translated: {translated}")
    print(f"  Unchanged: {unchanged}")
    print(f"  Total: {len(strings)}")

