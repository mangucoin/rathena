def tr(text):
    """Main translation function."""
    if not text or not text.strip():
        return text

    t = text.strip()

    # Pure punctuation
    if all(c in '.!?*~-() \t\r\n' for c in t):
        return text

    # Preserve leading/trailing whitespace
    ws_before = text[:len(text) - len(text.lstrip())]
    ws_after = text[len(text.rstrip()):]

    # Exact match
    if t in EXACT:
        return ws_before + EXACT[t] + ws_after

    # Handle color codes
    if '^' in t and re.search(r'\^[0-9a-fA-F]{6}', t):
        parts = re.split(r'(\^[0-9a-fA-F]{6})', t)
        result = []
        for part in parts:
            if re.match(r'^\^[0-9a-fA-F]{6}$', part):
                result.append(part)
            elif part.strip() in EXACT:
                result.append(EXACT[part.strip()])
            else:
                result.append(translate_sentence(part))
        return ws_before + ''.join(result) + ws_after

    # Sentence-level translation
    translated = translate_sentence(t)
    return ws_before + translated + ws_after

